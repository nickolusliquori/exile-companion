#!/usr/bin/env python3
"""Build app/mapmods.js (map modifier families for the search-string builder) from a RePoE mods.json.
Usage: python3 scripts/mapmods.py <folder with mods.json> <patch version>"""
import json, os, re, sys
src, version = sys.argv[1], sys.argv[2]
mods = json.load(open(os.path.join(src, "mods.json"), encoding="utf-8"))
TAGS = {"low_tier_map", "mid_tier_map", "top_tier_map", "uber_tier_map", "default"}
def clean(t):
    t = re.sub(r"\[([^\]|]+)\|([^\]]+)\]", r"\2", t)
    return re.sub(r"\[([^\]]+)\]", r"\1", t)
GENERIC = re.compile(r"increased (Atlas Drops|Rarity of Items found|Quantity of Items found|Pack Size)|% (increased |more )?Monster pack size|more (Maps|Currency|Threads|Scarabs) found in Area", re.I)
fam = {}
for mid, m in mods.items():
    if m.get("domain") != "area" or m.get("generation_type") not in ("prefix", "suffix"):
        continue
    tags = {w["tag"] for w in m.get("spawn_weights", []) if w["weight"] > 0}
    if not tags & TAGS:
        continue
    lines = [clean(l) for l in (m.get("text") or "").split("\n") if l.strip()]
    keep = [l for l in lines if not GENERIC.search(l)]
    if not keep:
        continue
    text = " / ".join(keep)
    key = re.sub(r"\(?[+-]?\d+(\.\d+)?(-\d+(\.\d+)?)?\)?", "#", text)
    f = fam.setdefault(key, {"x": key, "g": m["generation_type"][0], "uber": False, "v": []})
    f["uber"] = f["uber"] or any("uber" in t for t in tags)
    if text not in f["v"]:
        f["v"].append(text)
out = sorted(fam.values(), key=lambda f: (f["uber"], f["g"], f["x"]))
bases = json.load(open(os.path.join(src, "base_items.json"), encoding="utf-8"))
names = sorted({b["name"] for b in bases.values() if b.get("item_class") == "Map" and b.get("name") and b.get("release_state") == "released"})
js = ("/* Map modifier families for the search-string builder. Generated by scripts/mapmods.py from the RePoE export "
      f"(https://repoe-fork.github.io, MIT) of Path of Exile {version}. Game data (c) Grinding Gear Games. */\n"
      "window.MAPMOD_DATA=" + json.dumps({"v": version, "mods": out, "names": names}, separators=(",", ":"), ensure_ascii=False) + ";\n")
open(os.path.join(os.path.dirname(__file__), "..", "app", "mapmods.js"), "w", encoding="utf-8").write(js)
print(len(out), "families,", len(names), "map names,", f"{len(js)/1024:.0f} KB")
